"""Canonical schema export and read-only drift detection."""

import argparse
import json
from pathlib import Path

from src.api.app import create_app
from src.api.routes.control import router as control_router
from src.api.routes.health import HealthResponse, ReadinessResponse
from src.application.control import CancelCase, CreateBinding, CreateCase
from src.domain.models import (
    Check,
    MigrationPlan,
    PatchProposal,
    Policy,
    PublicationRequest,
    ValidationEvidence,
)

ROOT = Path(__file__).resolve().parents[1]


def generated_files() -> dict[Path, str]:
    files = {}
    for model in [
        Check,
        MigrationPlan,
        PatchProposal,
        ValidationEvidence,
        PublicationRequest,
        Policy,
        HealthResponse,
        ReadinessResponse,
        CreateBinding,
        CreateCase,
        CancelCase,
    ]:
        files[Path("contracts/json-schema") / f"{model.__name__}.json"] = (
            json.dumps(model.model_json_schema(), indent=2, sort_keys=True) + "\n"
        )
    contract_app = create_app()
    contract_app.include_router(control_router, prefix="/api/v1")
    files[Path("contracts/openapi/control.json")] = (
        json.dumps(contract_app.openapi(), indent=2, sort_keys=True) + "\n"
    )
    fields = []
    for name, field in HealthResponse.model_json_schema()["properties"].items():
        if "const" not in field:
            raise ValueError("Extend the type generator for non-literal health fields")
        fields.append(f"  {name}: {json.dumps(field['const'])};")
    types = ["export interface HealthResponse {", *fields, "}"]
    for model in [CreateBinding, CreateCase, CancelCase]:
        schema = model.model_json_schema()
        types.extend(["", f"export interface {model.__name__} {{"])
        for name, field in schema["properties"].items():
            ts_type = {"string": "string", "integer": "number"}.get(field.get("type"))
            if ts_type is None or name not in schema["required"]:
                raise ValueError(f"Unsupported generated request field: {model.__name__}.{name}")
            types.append(f"  {name}: {ts_type};")
        types.append("}")
    files[Path("frontend/src/shared/api/generated.ts")] = (
        "// Generated by scripts/generate_contracts.py. Do not edit.\n" + "\n".join(types) + "\n"
    )
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = generated_files()
    if args.check:
        drift = [
            str(path)
            for path, content in files.items()
            if not (ROOT / path).is_file() or (ROOT / path).read_text() != content
        ]
        extras = {
            p.relative_to(ROOT) for p in (ROOT / "contracts/json-schema").glob("*.json")
        } - files.keys()
        if drift or extras:
            raise SystemExit(
                f"Generated contract drift: {drift + [str(p) for p in extras]}. Run make schemas."
            )
        print("PASS: generated contracts match canonical sources")
    else:
        for path, content in files.items():
            (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / path).write_text(content)


if __name__ == "__main__":
    main()
