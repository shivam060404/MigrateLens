"""Record exact installed dependency closure for this environment; no registry claims.

Use uv pip compile for future reviewed lock refreshes when registry access is available.
"""

import importlib.metadata
import tomllib
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
project = tomllib.loads((ROOT / "backend/pyproject.toml").read_text())
pending = project["project"]["dependencies"] + project["dependency-groups"]["dev"]
seen: dict[str, str] = {}
while pending:
    req = Requirement(pending.pop())
    if req.marker and not req.marker.evaluate():
        continue
    name = canonicalize_name(req.name)
    if name in seen:
        continue
    dist = importlib.metadata.distribution(req.name)
    if req.specifier and dist.version not in req.specifier:
        raise RuntimeError(f"Installed {name} does not satisfy {req.specifier}")
    seen[name] = dist.version
    pending.extend(dist.requires or [])
(ROOT / "backend/requirements.lock").write_text(
    "# Exact installed closure: Python 3.14, macOS arm64. No hash or cross-platform claim.\n"
    "# Generated by scripts/snapshot_python_environment.py; install with uv pip sync.\n"
    + "\n".join(f"{name}=={version}" for name, version in sorted(seen.items()))
    + "\n"
)
